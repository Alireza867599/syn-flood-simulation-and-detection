def format_ratio(value: float) -> str:
    """Format an infinite or finite ratio for display."""
    return "∞" if value == float("inf") else f"{value:.2f}"


def print_detection_results(windows: list[TrafficWindow], attacks: list[dict[str, object]]) -> None:
    """Print the detector output in a report format."""
    print("\n" + "=" * 80)
    print("TASK 3 — SYN FLOOD ATTACK DETECTION RESULTS")
    print("=" * 80)
    print(f"Total time windows analyzed : {len(windows)}")
    print(f"Time window size            : {TIME_WINDOW}s")
    print(f"Attack periods detected     : {len(attacks)}")
    print("-" * 80)
    print("Thresholds:")
    print(f"  Minimum SYN count          : {SYN_MIN_THRESHOLD}")
    print(f"  SYN/ACK ratio threshold    : {RATIO_THRESHOLD}:1")
    print(f"  Minimum dropped SYNs       : {DROPPED_THRESHOLD}")
    print(f"  Backlog pressure threshold : {BACKLOG_PRESSURE_THRESHOLD * 100:.0f}%")

    if not attacks:
        print("\nNO ATTACKS DETECTED")
        print("=" * 80)
        return

    print("\n" + "=" * 80)
    print("ATTACK ALERTS")
    print("=" * 80)

    for index, attack in enumerate(attacks, 1):
        attack_windows = attack["windows"]
        total_syn = sum(w.syn_count for w in attack_windows)
        total_ack = sum(w.ack_count for w in attack_windows)
        total_dropped = sum(w.dropped_count for w in attack_windows)
        avg_rejection = sum(w.rejection_rate for w in attack_windows) / len(attack_windows)
        finite_ratios = [w.syn_ack_ratio for w in attack_windows if w.syn_ack_ratio != float("inf")]
        avg_ratio = sum(finite_ratios) / len(finite_ratios) if finite_ratios else float("inf")

        print(f"\nATTACK #{index}")
        print(f"  Start time        : {attack['start']:.2f}s")
        print(f"  End time          : {attack['end']:.2f}s")
        print(f"  Duration          : {attack['duration']:.2f}s")
        print(f"  Windows           : {len(attack_windows)}")
        print(f"  Total SYN         : {total_syn}")
        print(f"  Total ACK         : {total_ack}")
        print(f"  Total dropped     : {total_dropped}")
        print(f"  Avg SYN/ACK ratio : {format_ratio(avg_ratio)}:1")
        print(f"  Avg rejection     : {avg_rejection * 100:.1f}%")

        print("\n  Detailed timeline:")
        print("      Time |   SYN |   ACK |  Drop |    Ratio |  Reject%")
        print("  ---------+-------+-------+-------+----------+---------")
        for window in attack_windows:
            print(
                f"  {window.timestamp:8.2f} | "
                f"{window.syn_count:5d} | "
                f"{window.ack_count:5d} | "
                f"{window.dropped_count:5d} | "
                f"{format_ratio(window.syn_ack_ratio):>8s} | "
                f"{window.rejection_rate * 100:7.1f}%"
            )

    print("\nRecommendations:")
    print("  - Enable SYN cookies or stateless validation.")
    print("  - Apply per-source rate limiting.")
    print("  - Increase backlog/worker capacity only together with rate controls.")
    print("  - Compare Task 1 and Task 2 using the same traffic scenario.")
    print("=" * 80)


